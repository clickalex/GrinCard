#!/usr/bin/env node
/*!
 * tools/build-templates.js — validates contributed card templates and keeps
 * card-templates/community/index.json in sync with the files on disk.
 *
 * Why this exists: a static site cannot list a directory, so the gallery and the
 * builder need a manifest to know which community templates to load. Hand-writing
 * one is exactly the kind of thing a contributor forgets, so:
 *
 *   npm run build:templates    regenerate the manifest (also runs at deploy time)
 *   node tools/build-templates.js --check    CI: fail if invalid or out of date
 *
 * A rejected template prints the reason and fails the build rather than silently
 * rendering a broken card on someone's printed stationery.
 *
 * Usage:
 *   node tools/build-templates.js [--check] [--json]
 */
'use strict';

const fs = require('fs');
const path = require('path');
const CardTemplates = require('../card-templates/card-templates.js');

const ROOT = path.resolve(__dirname, '..');
const DIR = path.join(ROOT, 'card-templates', 'community');
const MANIFEST = path.join(DIR, 'index.json');

function args() {
  const out = { check: false, json: false };
  process.argv.slice(2).forEach((a) => {
    if (a === '--check') out.check = true;
    if (a === '--json') out.json = true;
    if (a === '--help' || a === '-h') out.help = true;
  });
  return out;
}

/** Every .js file in the community folder, sorted so output is deterministic. */
function templateFiles() {
  if (!fs.existsSync(DIR)) return [];
  return fs.readdirSync(DIR)
    .filter((f) => f.endsWith('.js'))
    .sort();
}

/** Load one contribution the same way the browser would, without executing side effects twice. */
function loadTemplate(file) {
  const full = path.join(DIR, file);
  try {
    // eslint-disable-next-line import/no-dynamic-require
    const mod = require(full);
    if (!mod || typeof mod !== 'object') {
      return { file, error: 'module did not export a template object' };
    }
    return { file, template: mod };
  } catch (err) {
    return { file, error: 'could not be loaded: ' + (err && err.message) };
  }
}

function readManifest() {
  if (!fs.existsSync(MANIFEST)) return null;
  try {
    return JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
  } catch (err) {
    return { parseError: String(err.message) };
  }
}

/**
 * The manifest we would write. `templates` is load order; `order` lets a
 * contributor float a template to the top of the gallery without a code change.
 */
function buildManifest(entries) {
  const templates = entries.map((e) => {
    const t = e.template;
    const item = {
      file: e.file,
      id: t.id,
      name: t.name,
      author: t.author || null,
      description: t.description || null,
      license: t.license || 'MIT'
    };
    if (typeof t.order === 'number') item.order = t.order;
    return item;
  });
  templates.sort((a, b) => {
    const ao = typeof a.order === 'number' ? a.order : 100;
    const bo = typeof b.order === 'number' ? b.order : 100;
    if (ao !== bo) return ao - bo;
    return a.file < b.file ? -1 : a.file > b.file ? 1 : 0;
  });

  return {
    $comment: [
      'Generated by tools/build-templates.js — do not edit by hand.',
      'Add a template by dropping a self-registering .js file in this folder and',
      'running `npm run build:templates`. CI verifies this file matches the folder.'
    ],
    generated_at: new Date().toISOString().slice(0, 10),
    count: templates.length,
    templates: templates.map((t) => {
      const copy = Object.assign({}, t);
      delete copy.order;
      return copy;
    }),
    order: templates.filter((t) => typeof t.order === 'number').map((t) => t.file)
  };
}

function main() {
  const opts = args();
  if (opts.help) {
    console.log('Usage: node tools/build-templates.js [--check] [--json]');
    return 0;
  }

  const files = templateFiles();
  const loaded = files.map(loadTemplate);
  const errors = [];
  const warnings = [];
  const good = [];

  // Core ids are taken; a contribution may not shadow them.
  const seen = new Set(CardTemplates.TEMPLATES.map((t) => t.id));

  loaded.forEach((entry) => {
    if (entry.error) {
      errors.push(entry.file + ': ' + entry.error);
      return;
    }
    const t = entry.template;
    if (seen.has(t.id)) {
      errors.push(entry.file + ': id "' + t.id + '" is already used by another template ' +
        '(ids must be unique across core and community)');
      return;
    }
    const check = CardTemplates.validateTemplate(t);
    check.errors.forEach((e) => errors.push(entry.file + ': ' + e));
    check.warnings.forEach((w) => warnings.push(entry.file + ': ' + w));
    if (check.ok) {
      seen.add(t.id);
      good.push(entry);
    }
  });

  // A manifest line pointing at nothing is a broken gallery entry.
  const existing = readManifest();
  if (existing && !existing.parseError && Array.isArray(existing.templates)) {
    const onDisk = new Set(files);
    existing.templates.forEach((item) => {
      if (!onDisk.has(item.file)) {
        errors.push('index.json lists "' + item.file + '" but that file is not in the folder');
      }
    });
  } else if (existing && existing.parseError) {
    errors.push('index.json is not valid JSON: ' + existing.parseError);
  }

  const manifest = buildManifest(good);
  const serialized = JSON.stringify(manifest, null, 2) + '\n';
  const current = fs.existsSync(MANIFEST) ? fs.readFileSync(MANIFEST, 'utf8') : null;

  // generated_at changes daily; ignore it when comparing so an unchanged folder
  // does not look dirty in CI.
  const comparable = (text) => {
    if (text == null) return null;
    try {
      const obj = JSON.parse(text);
      delete obj.generated_at;
      return JSON.stringify(obj, null, 2);
    } catch (e) {
      return text;
    }
  };
  const stale = comparable(current) !== comparable(serialized);

  if (errors.length) {
    console.error('Community templates: ' + errors.length + ' problem(s)');
    errors.forEach((e) => console.error('  ✗ ' + e));
    warnings.forEach((w) => console.warn('  ! ' + w));
    return 1;
  }

  if (opts.check) {
    if (stale) {
      console.error('card-templates/community/index.json is out of date.');
      console.error('  Files on disk: ' + (files.join(', ') || '(none)'));
      console.error('  Run: npm run build:templates');
      return 1;
    }
    if (opts.json) console.log(JSON.stringify({ ok: true, count: good.length }, null, 2));
    else console.log('Community templates OK: ' + good.length + ' valid, manifest up to date.');
    warnings.forEach((w) => console.warn('  ! ' + w));
    return 0;
  }

  if (stale || current == null) {
    fs.writeFileSync(MANIFEST, serialized, 'utf8');
    console.log('Wrote card-templates/community/index.json (' + good.length + ' template' +
      (good.length === 1 ? '' : 's') + ')');
  } else {
    console.log('card-templates/community/index.json already up to date (' + good.length + ' template' +
      (good.length === 1 ? '' : 's') + ')');
  }
  warnings.forEach((w) => console.warn('  ! ' + w));
  good.forEach((e) => console.log('  ✓ ' + e.file + ' → ' + e.template.id + ' (“' + e.template.name + '”)'));
  return 0;
}

if (require.main === module) process.exit(main());
module.exports = { main, buildManifest, loadTemplate, DIR, MANIFEST };
